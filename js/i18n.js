  function makeT(lang) {
    const dict = lang === 'he' ? he : en;
    return function t(key, vars) {
      let s = dict[key];
      if (s === undefined) s = en[key];
      if (typeof s !== 'string') return s;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
      return s;
    };
  }

  // Hebrew has a dual form for days ("יומיים")
  function daysPhrase(n, lang, t) {
    if (n === 0) return t('today');
    if (n === 1) return t('tomorrow');
    if (lang === 'he' && n === 2) return 'בעוד יומיים';
    return t('inDays', { n });
  }

  // 95 minutes → "1h 35m" / "1 ש׳ 35 ד׳"
  function durationText(mins, lang) {
    mins = Math.max(0, Math.round(mins));
    const h = Math.floor(mins / 60);
    const m = mins % 60;
    const hu = lang === 'he' ? ' ש׳' : 'h';
    const mu = lang === 'he' ? ' ד׳' : 'm';
    if (h && m) return h + hu + ' ' + m + mu;
    if (h) return h + hu;
    return m + mu;
  }

  Object.assign(SP, { i18n: { en, he, makeT, daysPhrase, durationText } });
